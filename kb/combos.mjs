// D9：「當令」只指旺氣；旺氣＋生氣合稱「生旺」。程式判斷仍用旺氣＋生氣，對外文字一律寫「生旺」。
const QI_TIMELY = ['旺氣', '生氣'];   // 生旺（旺氣＝當令、生氣＝將旺）
const QI_FUTURE = ['進氣'];   // 未來之氣（次生氣）：還不到生旺，但不算衰敗
const CN_NUM = ['', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
// 寫進文字時，旺氣、生氣各補一句白話，免得把生氣誤讀成「當令」
const QI_WORD = { 旺氣: '旺氣（當令）', 生氣: '生氣（將旺）' };
const qiWord = (q) => QI_WORD[q] || q;

// 只有一顆星生旺時，另一顆失令（退氣、衰氣、死氣、煞氣）要補的一句提醒。

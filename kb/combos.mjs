const isStar = (n) => Number.isInteger(n) && n >= 1 && n <= 9;

/** 另一顆星不在生旺時補的一句。role：'山星'｜'向星' */
function remind(role, star, qi) {
  const name = STAR_NAMES[star];
  if (QI_FUTURE.includes(qi)) {
    const side = role === '山星' ? '人丁健康' : '財運';
    return `${role}${name}屬${qi}，還不到生旺，${side}這一面的吉應較淡。`;
  }
  const hint = (role === '山星' ? HINT_M : HINT_F)[star];
  return `提醒：${role}${name}屬${qi}，已經失令，${hint}。`;
}

/**
 * 某一宮的山向星組合，在某一運怎麼看。
 *   m＝山星、f＝向星、period＝元運（1–9）
 * 回傳 { key, title, luck, text, kidBad }（kidBad：Q6，傳統明講對小孩不利的組合，跟 COMBOS[key].kidBad 同值）
 *   text＝基本含意 ＋ 一句兩星在該運的旺衰 ＋ timely 或 untimely ＋ 建議（fix）
 *     任一顆生旺（旺氣／生氣）→ 用 timely；另一顆不在生旺時補一句提醒（山星講人丁健康、向星講財）。
 *     兩顆都不在生旺 → 用 untimely；其中有進氣（未來之氣）時註明凶應較輕。
 *     文字裡旺氣寫「旺氣（當令）」、生氣寫「生氣（將旺）」，合稱「生旺」（D9）。
 *   luck：含五黃且不是五運 → 凶；兩星都生旺 → 吉；其餘沿用 COMBOS 的 luck
 * period 不是 1–9 時不判旺衰，只回基本含意與建議。m、f 不是 1–9 時回空白結果，不丟例外。
 */
export function comboOf(m, f, period) {
  const mi = Number(m);
  const fi = Number(f);
  if (!isStar(mi) || !isStar(fi)) return { key: '', title: '', luck: '平', text: '', kidBad: false };

  const key = `${mi}${fi}`;
  const c = COMBOS[key];
  const hasFive = mi === 5 || fi === 5;
  const p = Number(period);

  if (period === null || period === undefined || period === '' || !isStar(p)) {
    return { key, title: c.title, luck: hasFive ? '凶' : c.luck, text: `${c.text}建議：${c.fix}`, kidBad: c.kidBad === true };
  }

  const qm = qiOf(mi, p);
  const qf = qiOf(fi, p);
  const mT = QI_TIMELY.includes(qm);
  const fT = QI_TIMELY.includes(qf);
  const nm = STAR_NAMES[mi];
  const nf = STAR_NAMES[fi];
  const yun = `${CN_NUM[p]}運`;

  let luck = c.luck;
  if (hasFive && p !== 5) luck = '凶';
  else if (mT && fT) luck = '吉';

  // 本性屬吉的組合（luck 沿用為吉）卻要列失令之應時，先交代一句，免得「吉」跟下面的提醒看起來互相矛盾
  const SOFT = '這一組本性屬吉，不在生旺時吉力打折，下面是要留意的地方。';

  let lead;
  let body;
  let extra = '';
  if (mi === fi) {
    if (mT) {
      lead = `${yun}${nm}屬${qiWord(qm)}，山星向星同屬生旺。`;
      body = c.timely;
    } else if (QI_FUTURE.includes(qm)) {
      lead = `${yun}${nm}屬${qm}，是未來之氣，還不到生旺。`;
      lead += luck === '吉' ? SOFT : '下面的凶應較輕，仍宜提防。';
      body = c.untimely;
    } else {
      lead = `${yun}${nm}屬${qm}，山星向星都已失令。`;
      if (luck === '吉') lead += SOFT;
      body = c.untimely;
    }
  } else if (mT && fT) {
    lead = `${yun}山星${nm}屬${qiWord(qm)}、向星${nf}屬${qiWord(qf)}，兩星同屬生旺。`;
    body = c.timely;
  } else if (mT) {
    lead = `${yun}山星${nm}屬${qiWord(qm)}，是生旺之星。`;
    body = c.timely;
    extra = remind('向星', fi, qf);
  } else if (fT) {
    lead = `${yun}向星${nf}屬${qiWord(qf)}，是生旺之星。`;
    body = c.timely;
    extra = remind('山星', mi, qm);
  } else {
    lead = `${yun}山星${nm}屬${qm}、向星${nf}屬${qf}，都不在生旺。`;
    const future = [];
    if (QI_FUTURE.includes(qm)) future.push(nm);
    if (QI_FUTURE.includes(qf)) future.push(nf);
    if (luck === '吉') {
      if (future.length) lead += `其中${future.join('、')}是未來之氣。`;
      lead += SOFT;
    } else if (future.length) {
      lead += `其中${future.join('、')}是未來之氣，凶應較輕，仍宜提防。`;
    }
    body = c.untimely;
  }

  // fix 多半是寫給失令時用的。遇到「生旺而不必化解」的情形，先交代一句，免得跟上面的吉應互相矛盾：
  //   五運五黃當令 → 針對五黃的化解可以從寬；
  //   本性屬凶或平的組合（鬥牛、交劍…）兩星都生旺 → 化解留到失令或流年凶星飛到時再用。
  if (hasFive && p === 5) {
    extra += '五運五黃當令，不作煞論，下面針對五黃的化解可以從寬。';
  } else if (mT && fT && c.luck !== '吉') {
    extra += '兩星同屬生旺時不必急著化解，下面的做法留到失令或流年凶星飛到時再用。';
  }

  return { key, title: c.title, luck, text: `${c.text}${lead}${body}${extra}建議：${c.fix}`, kidBad: c.kidBad === true };
}

/** 清單就是一般陣列；另外讓它直接接進字串時用「、」連接（不會變成半形逗號）。 */
function list(...xs) {
  Object.defineProperty(xs, 'toString', { value() { return this.join('、'); }, enumerable: false });
  return xs;
}


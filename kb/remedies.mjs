/**
 * Q2：這一宮不宜放水時取「不放水」的版本。field＝'items'｜'forDoor'｜'method'；
 * 有 xxxNoWater 就回它，沒有就回原本的（原本就沒叫人放水）。boost 也是條目，可以直接傳 STAR_REMEDY[1].boost。
 */
export function noWaterOf(entry, field) {
  if (!entry || typeof entry !== 'object') return undefined;
  const dry = entry[`${field}NoWater`];
  return dry !== undefined ? dry : entry[field];
}

/**
 * Y1：大門納衰氣 byStar 的一條＝{ text, noWaterText }。
 * noWaterText 沒給＝這顆星本來就沒叫人放水，跟 text 一樣。接進字串時等於 text。
 */
function doorLine(text, noWaterText) {
  const o = { text, noWaterText: noWaterText || text };
  Object.defineProperty(o, 'toString', { value() { return this.text; }, enumerable: false });
  return Object.freeze(o);
}


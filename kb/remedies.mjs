/**
 * with25 的形狀：當 { method, items } 讀（x.method、x.items），也可以直接當做法清單用
 * （Array.isArray(x) 為真、[...x] 就是 items、接進字串用「、」連接）。
 * method、items 設成不可列舉，所以展開、走訪陣列時只會拿到一條條做法，不會重複。
 */
function remedyObj(method, items) {
  const o = list(...items);
  Object.defineProperty(o, 'method', { value: method, enumerable: false });
  Object.defineProperty(o, 'items', { value: items, enumerable: false });
  return o;
}

